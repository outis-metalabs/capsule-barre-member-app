"""Cue Book (CB-10): rebuild assets/cue-book/lessons.js from the webbook's embedded data.
Usage: cue_book_extract.py <webbook index.html> [out.js]
The webbook (https://effervescent-biscuit-dddbef.netlify.app/) is a bundled single page; its book data
(articles, pose bank, audio map) and Cici pose media live gzip+base64 in the __bundler/manifest script."""
import sys, re, json, base64, gzip
src = open(sys.argv[1], encoding='utf-8').read()
out = sys.argv[2] if len(sys.argv) > 2 else 'assets/cue-book/lessons.js'
man = json.loads(re.search(r'<script type="__bundler/manifest">\s*(.*?)\s*</script>', src, re.S).group(1))
ext = {e['id']: e['uuid'] for e in json.loads(re.search(r'<script type="__bundler/ext_resources">\s*(.*?)\s*</script>', src, re.S).group(1))}
def res(k):
  v = man[ext[k]]; d = base64.b64decode(v['data']); return json.loads(gzip.decompress(d) if v.get('compressed') else d)
book, media = res('bookData'), res('ciciMedia')
TRACK = {'초급': 'basic', '중급': 'flow'}  # '1:1 레슨' (lessons 25-36) is out of scope
PH = 'placeholder://cue-book/audio/'  # PLACEHOLDER: no recording in the webbook for this sentence
lessons, stats = {}, {'cues': 0, 'audio': 0, 'img': 0, 'pos': 0}
for i, a in enumerate(book['articles']):
  tr = TRACK.get(a['track'])
  if not tr: continue
  lid = f"{tr}-{a['week']:02d}"; pos, cues = [], []
  for pi, n in enumerate(a['ids']):
    p = book['bank'][n - 1]; img = (media.get(str(n)) or {}).get('img')
    stats['pos'] += 1; stats['img'] += bool(img)
    pos.append({'poseId': n, 'image': img, 'nameEn': None, 'nameKr': p['easy_title'], 'titleKr': p['title']})
    for ci, (en, kr) in enumerate(p['cues']):
      url = book['audio'].get(en); stats['cues'] += 1; stats['audio'] += bool(url)
      cues.append({'en': en, 'kr': kr, 'position': pi,
                   'audioNormalUrl': url or f'{PH}{lid}/{pi}-{ci}-normal.mp3',
                   'audioSlowUrl': url or f'{PH}{lid}/{pi}-{ci}-slow.mp3',
                   'audioPlaceholder': not url})
  lessons[lid] = {'id': lid, 'track': tr, 'number': a['week'], 'bookNumber': i + 1, 'title': a['title'], 'titleLang': 'kr',
                  'review': a['week'] % 4 == 0, 'positions': pos, 'cues': cues}
assert len(lessons) == 24 and all(len(l['positions']) == 5 for l in lessons.values())
hdr = ('/* Cue Book with Cici: lesson content map (CB-10). GENERATED by scripts/cue_book_extract.py from the webbook\n'
       '   https://effervescent-biscuit-dddbef.netlify.app/ . Do not edit by hand; re-run the script.\n'
       '   Loaded ONLY when FLAGS.cueBook is on (CB-1). basic-01..12 = webbook lessons 01-12, flow-01..12 = 13-24; 1:1 (25-36) excluded.\n'
       '   audioSlowUrl: the webbook has one recording per sentence and plays it at 0.75x for "slow"; play slow URLs at CUE_BOOK_SLOW_RATE.\n'
       '   audioPlaceholder:true => no recording exists yet, URL is a placeholder:// stub. nameEn is null: the webbook has no English pose names.\n'
       f"   {stats['cues']} cues, {stats['audio']} with real audio; {stats['pos']} positions, {stats['img']} with images. */\n")
open(out, 'w', encoding='utf-8').write(hdr + 'window.CUE_BOOK_SLOW_RATE = 0.75;\nwindow.CUE_BOOK_LESSONS = ' + json.dumps(lessons, ensure_ascii=False, indent=1) + ';\n')
print(stats)
